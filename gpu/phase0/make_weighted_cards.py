"""Write the stock weighted-mode cards that measure the running-pMax bias of unweighted `se`.

Each reference point (base card x m_chi, as in make_ref_cards.py) gets R replicas with their own seeds, run with
`weighted true` and `output_mode summary`: no event file, no burn-in, and the run stops at max_trials. The spread of
the replicas gives the statistical error of weighted `se` (the event file cannot: it stores one DM weight per event).
Outputs land in cards/ref_w/<base>_m<MeV>_r<k>.dat; run them with `run_stock.sh O2 ref_w/<stem>`.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).parent
TRIALS = {  # base card stem -> total weighted trials per reference point, split over the replicas
    "mb_pi0_m005": 500_000_000,
    "he_pi0_cuboid_m005": 40_000_000,
    "mb_brem_m005": 20_000_000,
    "he_brem_cuboid_m005": 20_000_000,
    # eta (appended so the earlier cards keep their seeds). bpmt_k0 shares BMPT's running-maximum bar, whose bias
    # shrinks with run length (5e6-trial pi0 replicas came out 0.2 % low), so its replicas are 2.5e7 trials each.
    "mb_eta_m005": 500_000_000,
    "he_eta_cuboid_m005": 200_000_000,
    # particle_list (appended): no parent sampler, so no running-maximum bias in the parents
    "mb_list_m005": 500_000_000,
    "he_list_cuboid_m005": 40_000_000,
}
MASSES_MEV = [1, 5, 20, 45]
SEED0 = 2026102900


def set_key(lines, key, value, append=False):
    out, done = [], False
    for line in lines:
        if line.split()[:1] == [key]:
            out.append(f"{key} {value}")
            done = True
        else:
            out.append(line)
    if not done:
        if not append:
            raise KeyError(f"{key} not in base card")
        out.append(f"{key} {value}")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--replicas", type=int, default=8)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    outdir = HERE / "cards" / "ref_w"
    manifest, seed = [], SEED0
    for base, total in TRIALS.items():
        if total % args.replicas:
            raise ValueError(f"{base}: {total} trials do not split into {args.replicas} replicas")
        per = total // args.replicas
        lines = (HERE / "cards" / f"{base}.dat").read_text().splitlines()
        stem_root = base.rsplit("_m", 1)[0]
        for mev in MASSES_MEV:
            for k in range(args.replicas):
                seed += 1
                stem = f"{stem_root}_m{mev:03d}_r{k}"
                card = lines
                card = set_key(card, "dark_matter_mass", f"{mev / 1000:g}")
                card = set_key(card, "seed", seed)
                card = set_key(card, "samplesize", 1_000_000_000)
                card = set_key(card, "max_trials", per)
                card = set_key(card, "output_mode", "summary")
                card = set_key(card, "weighted", "true", append=True)
                card[0] = (f"# Phase 0 stock weighted reference, generated by make_weighted_cards.py from {base}.dat "
                           f"(m_chi {mev} MeV, replica {k}).")
                manifest.append({"stem": f"ref_w/{stem}", "base": base, "m_chi_MeV": mev, "replica": k,
                                 "seed": seed, "max_trials": per})
                if not args.dry_run:
                    outdir.mkdir(parents=True, exist_ok=True)
                    (outdir / f"{stem}.dat").write_text("\n".join(card) + "\n")
    if not args.dry_run:
        (outdir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    print(f"{len(manifest)} cards, seeds {manifest[0]['seed']}-{manifest[-1]['seed']}")


if __name__ == "__main__":
    main()
