"""Write the Phase 0 stock reference cards: the four base cards at several m_chi, each with its own seed.

pi0 cards stop at a target accepted-event count (samplesize, with a max_trials guard); brem cards stop at a fixed
trial count. Outputs land in cards/ref/<base>_m<MeV>.dat; run them with `run_stock.sh O2 ref/<stem>`.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).parent
BASES = {  # base card stem -> (samplesize, max_trials)
    "mb_pi0_m005": (1_000_000, 2_000_000_000),
    "he_pi0_cuboid_m005": (1_000_000, 1_000_000_000),
    "mb_brem_m005": (1_000_000_000, 20_000_000),
    "he_brem_cuboid_m005": (1_000_000_000, 20_000_000),
    # eta (added 2026-10-29; appended so the earlier cards keep their seeds): 3.2e-4 / 6.1e-3 accepted per trial.
    # Stock narrows max_trials to int, so mb_eta's 5e9 wraps to 705,032,704: those runs stop there (about 2.3e5 events)
    "mb_eta_m005": (1_000_000, 5_000_000_000),
    "he_eta_cuboid_m005": (1_000_000, 1_000_000_000),
    # particle_list (added 2026-10-29; base cards and lists from make_lists.py): 8.5e-4 / 1.3e-2 accepted per trial
    "mb_list_m005": (1_000_000, 4_000_000_000),
    "he_list_cuboid_m005": (1_000_000, 1_000_000_000),
    # off-shell pi0 decay (added 2026-10-29; m_V 0.2 GeV, make_offshell_cards.py)
    "mb_offshell_m005": (1_000_000, 4_000_000_000),
    "he_offshell_cuboid_m005": (1_000_000, 1_000_000_000),
}
MASSES_MEV = [1, 5, 20, 45]
SEED0 = 2026102800
# The 5 MeV brem runs in out/<base>/O2 already have 2e7 trials and are reused, not regenerated.
REUSE = {("mb_brem_m005", 5), ("he_brem_cuboid_m005", 5)}


def set_key(lines, key, value):
    out, done = [], False
    for line in lines:
        if line.split()[:1] == [key]:
            out.append(f"{key} {value}")
            done = True
        else:
            out.append(line)
    if not done:
        raise KeyError(f"{key} not in base card")
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    outdir = HERE / "cards" / "ref"
    manifest, seed = [], SEED0
    for base, (samplesize, max_trials) in BASES.items():
        lines = (HERE / "cards" / f"{base}.dat").read_text().splitlines()
        stem_root = base.rsplit("_m", 1)[0]
        for mev in MASSES_MEV:
            seed += 1
            if (base, mev) in REUSE:
                manifest.append({"stem": f"{base}", "reused": f"out/{base}/O2", "m_chi_MeV": mev})
                continue
            stem = f"{stem_root}_m{mev:03d}"
            card = lines
            card = set_key(card, "dark_matter_mass", f"{mev / 1000:g}")
            card = set_key(card, "seed", seed)
            card = set_key(card, "samplesize", samplesize)
            card = set_key(card, "max_trials", max_trials)
            card[0] = f"# Phase 0 stock reference, generated by make_ref_cards.py from {base}.dat (m_chi {mev} MeV)."
            manifest.append({"stem": f"ref/{stem}", "base": base, "m_chi_MeV": mev, "seed": seed,
                             "samplesize": samplesize, "max_trials": max_trials})
            if not args.dry_run:
                outdir.mkdir(parents=True, exist_ok=True)
                (outdir / f"{stem}.dat").write_text("\n".join(card) + "\n")
    if not args.dry_run:
        (outdir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    for m in manifest:
        print(m)


if __name__ == "__main__":
    main()
