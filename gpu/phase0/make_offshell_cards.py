"""Write the off-shell base cards: the pi0 base cards with dark_photon_mass 0.2 GeV (above m_pi0, so pi0 -> gamma V*
-> gamma chi chi is off-shell at every m_chi) and their own seeds. make_ref_cards.py and make_weighted_cards.py
turn them into the reference sets.
"""
from pathlib import Path

HERE = Path(__file__).parent
CARDS = {  # off-shell base card stem -> (pi0 base card, seed)
    "mb_offshell_m005": ("mb_pi0_m005", 20261044),
    "he_offshell_cuboid_m005": ("he_pi0_cuboid_m005", 20261045),
}
M_V = 0.2


def main():
    for stem, (base, seed) in CARDS.items():
        out, done = [], set()
        for line in (HERE / "cards" / f"{base}.dat").read_text().splitlines():
            key = line.split()[:1]
            if key == ["dark_photon_mass"]:
                out.append(f"dark_photon_mass {M_V}")
                done.add("mv")
            elif key == ["seed"]:
                out.append(f"seed {seed}")
                done.add("seed")
            else:
                out.append(line)
        if done != {"mv", "seed"}:
            raise KeyError(f"{base}: missing {({'mv', 'seed'} - done)}")
        out[0] = f"# off-shell base card, generated by make_offshell_cards.py from {base}.dat (m_V {M_V} GeV)."
        (HERE / "cards" / f"{stem}.dat").write_text("\n".join(out) + "\n")
        print(f"cards/{stem}.dat")


if __name__ == "__main__":
    main()
