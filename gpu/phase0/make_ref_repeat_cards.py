"""Write repeat stock reference cards: cards/ref/<stem>.dat with the seed raised by --seed-offset, into cards/<outdir>/.
Run them with `run_stock.sh O2 <outdir>/<stem>`.

Usage: make_ref_repeat_cards.py <stem> [<stem> ...] [--seed-offset 1000000] [--outdir ref_r2]
"""
import argparse
from pathlib import Path

HERE = Path(__file__).parent


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("stems", nargs="+")
    ap.add_argument("--seed-offset", type=int, default=1_000_000)
    ap.add_argument("--outdir", default="ref_r2")
    args = ap.parse_args()
    out = HERE / "cards" / args.outdir
    out.mkdir(exist_ok=True)
    for stem in args.stems:
        lines = (HERE / "cards" / "ref" / f"{stem}.dat").read_text().splitlines()
        seeds = [i for i, line in enumerate(lines) if line.split()[:1] == ["seed"]]
        if len(seeds) != 1:
            raise ValueError(f"{stem}: {len(seeds)} seed lines")
        seed = int(lines[seeds[0]].split()[1]) + args.seed_offset
        lines[seeds[0]] = f"seed {seed}"
        lines[0] = f"# Repeat stock reference, generated by make_ref_repeat_cards.py from ref/{stem}.dat (seed {seed})."
        (out / f"{stem}.dat").write_text("\n".join(lines) + "\n")
        print(f"{args.outdir}/{stem}: seed {seed}")


if __name__ == "__main__":
    main()
