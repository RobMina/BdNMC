"""Write one long stock weighted run per he_pi0 reference mass, to separate BMPT's running-max parent clipping from
the signal running-pMax bias.

The 8 short weighted replicas (5e6 trials each, make_weighted_cards.py) each start a fresh BMPT running max, so they
carry 8x the early-parent clipping of one run. One weighted run as long as the unweighted reference (8.6e7 trials)
carries about as much clipping as that unweighted run. If clipping explains the port being above the short
replicas, this run moves up to the port. Outputs land in cards/ref_wl/<base>_m<MeV>.dat; run them with
`run_stock.sh O2 ref_wl/<stem>`.
"""
import argparse
import json
from pathlib import Path

from make_weighted_cards import MASSES_MEV, set_key

HERE = Path(__file__).parent
BASE = "he_pi0_cuboid_m005"
TRIALS = 86_000_000
SEED0 = 2026103100  # above the seeds used by make_weighted_cards.py (last 2026103028)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    outdir = HERE / "cards" / "ref_wl"
    lines = (HERE / "cards" / f"{BASE}.dat").read_text().splitlines()
    stem_root = BASE.rsplit("_m", 1)[0]
    manifest = []
    for k, mev in enumerate(MASSES_MEV):
        seed = SEED0 + k
        stem = f"{stem_root}_m{mev:03d}"
        card = lines
        card = set_key(card, "dark_matter_mass", f"{mev / 1000:g}")
        card = set_key(card, "seed", seed)
        card = set_key(card, "samplesize", 1_000_000_000)
        card = set_key(card, "max_trials", TRIALS)
        card = set_key(card, "output_mode", "summary")
        card = set_key(card, "weighted", "true", append=True)
        card[0] = (f"# Phase 0 long stock weighted run, generated by make_long_weighted_cards.py from {BASE}.dat "
                   f"(m_chi {mev} MeV).")
        manifest.append({"stem": f"ref_wl/{stem}", "base": BASE, "m_chi_MeV": mev, "seed": seed,
                         "max_trials": TRIALS})
        if not args.dry_run:
            outdir.mkdir(parents=True, exist_ok=True)
            (outdir / f"{stem}.dat").write_text("\n".join(card) + "\n")
    if not args.dry_run:
        (outdir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    print(f"{len(manifest)} cards, seeds {manifest[0]['seed']}-{manifest[-1]['seed']}")


if __name__ == "__main__":
    main()
