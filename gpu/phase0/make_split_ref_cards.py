"""Write split stock reference cards: each reference point of make_ref_cards.py (cards/ref/<stem>.dat) as N parts with
their own seeds, samplesize/N accepted events and a max_trials guard of max_trials/N, so the parts run in parallel
(one core each) and together hold the same number of events. merge_stock_parts.py joins the parts' electrons for V2
and compare_v.py combines their logs for V1 (config key "stock_runs").
Outputs land in cards/ref_s/<stem>_p<kk>.dat with cards/ref_s/MANIFEST.json. Seeds are numbered from SEED0 and must
not repeat any seed of any card under cards/.
"""
import argparse
import json
from pathlib import Path

from make_ref_cards import BASES, MASSES_MEV, set_key

HERE = Path(__file__).parent
PARTS = {  # base card stem -> number of parts; sized for about 10 min per part on a UVA standard core (container build)
    "mb_offshell_m005": 40,
    "he_offshell_cuboid_m005": 10,
}
SEED0 = 2026110000


def used_seeds(cards, skip):
    seeds = {}
    for p in cards.rglob("*.dat"):
        if p.parent == skip:
            continue
        for line in p.read_text().splitlines():
            if line.split()[:1] == ["seed"]:
                seeds[int(line.split()[1])] = p
    return seeds


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    cards = HERE / "cards"
    outdir = cards / "ref_s"
    taken = used_seeds(cards, outdir)
    manifest, seed = [], SEED0
    for base, n in PARTS.items():
        samplesize, max_trials = BASES[base]
        if samplesize % n or max_trials % n:
            raise ValueError(f"{base}: samplesize {samplesize} or max_trials {max_trials} does not split into {n}")
        stem_root = base.rsplit("_m", 1)[0]
        for mev in MASSES_MEV:
            point = f"{stem_root}_m{mev:03d}"
            lines = (cards / "ref" / f"{point}.dat").read_text().splitlines()
            for k in range(n):
                seed += 1
                if seed in taken:
                    raise ValueError(f"seed {seed} already used by {taken[seed]}")
                card = set_key(lines, "seed", seed)
                card = set_key(card, "samplesize", samplesize // n)
                card = set_key(card, "max_trials", max_trials // n)
                card[0] = (f"# Phase 0 split stock reference, generated by make_split_ref_cards.py from ref/{point}.dat "
                           f"(part {k} of {n}).")
                stem = f"{point}_p{k:02d}"
                manifest.append({"stem": f"ref_s/{stem}", "point": point, "part": k, "n_parts": n, "seed": seed,
                                 "samplesize": samplesize // n, "max_trials": max_trials // n})
                if not args.dry_run:
                    outdir.mkdir(parents=True, exist_ok=True)
                    (outdir / f"{stem}.dat").write_text("\n".join(card) + "\n")
    if not args.dry_run:
        (outdir / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    print(f"{len(manifest)} cards, seeds {manifest[0]['seed']}-{manifest[-1]['seed']}")


if __name__ == "__main__":
    main()
