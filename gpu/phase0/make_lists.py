"""Write the synthetic particle lists for the `particle_list` reference cards, and those cards.

Each list has N parent pi0 drawn from one of the analytic laws already validated against stock (Sanford-Wang at
8.9 GeV for `mb_list`, BMPT at 120 GeV on carbon for `he_list_cuboid`; the port's envelope sampler, fixed seed),
plus a synthetic decay vertex so that `particle_list_position` is exercised: x, y Gaussian (sigma 0.2 m), z uniform
in [0, 50] m, t = z / c. Rows are `px py pz E x y z t` (GeV, metres, seconds) at 12 significant digits; E is the
pi0 energy (stock ignores it and recomputes it from the mass).

The lists (lists/*.dat, about 130 MB each) are not tracked: rerun this script, which checks each file against the
sha256 in lists/MANIFEST.json if one is there. The base cards cards/<stem>.dat are the pi0 base cards with the
distribution swapped and a new seed. `particle_list_file` is relative to gpu/ (the port opens it from the working
directory, as stock does); run_stock.sh rewrites it to an absolute path for stock, which runs from the repo root.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys

import jax
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from bdnmc_jax import card as cardmod, parents, pipeline, rng  # noqa: E402
from bdnmc_jax.constants import speed_of_light  # noqa: E402

HERE = Path(__file__).parent
N = 1_000_000
LISTS = {  # list card stem -> (base card, list seed, card seed)
    "mb_list_m005": ("mb_pi0_m005", 20261040, 20261041),
    "he_list_cuboid_m005": ("he_pi0_cuboid_m005", 20261042, 20261043),
}


def draw(base, seed):
    _, _, (ch,) = pipeline.setup(cardmod.parse_card(HERE / "cards" / f"{base}.dat"), "envelope")
    nb = -(-N // rng.BLOCK)
    call = jax.jit(lambda b: parents.sample_block(ch.dist, rng.block_key(seed, 0, b), rng.BLOCK, ch.fmax,
                                                  ch.m_meson))
    p4 = np.concatenate([np.asarray(call(b)[0]) for b in range(nb)])[:N]
    rs = np.random.default_rng(seed)
    x, y = rs.normal(0.0, 0.2, N), rs.normal(0.0, 0.2, N)
    z = rs.uniform(0.0, 50.0, N)
    return np.column_stack([p4[:, 1], p4[:, 2], p4[:, 3], p4[:, 0], x, y, z, z / speed_of_light])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cards-only", action="store_true", help="write the base cards, not the lists")
    args = ap.parse_args()
    (HERE / "lists").mkdir(exist_ok=True)
    man_path = HERE / "lists" / "MANIFEST.json"
    manifest = json.loads(man_path.read_text()) if man_path.exists() else {}
    for stem, (base, list_seed, card_seed) in LISTS.items():
        name = stem.rsplit("_m", 1)[0]
        rel = f"phase0/lists/{name}.dat"
        if not args.cards_only:
            rows = draw(base, list_seed)
            text = (f"# synthetic pi0 list from make_lists.py: {base} law, seed {list_seed}, {N} rows\n"
                    "# px py pz E x y z t\n" + "\n".join(" ".join("%.12g" % v for v in r) for r in rows) + "\n")
            digest = hashlib.sha256(text.encode()).hexdigest()
            if name in manifest and manifest[name]["sha256"] != digest:
                raise RuntimeError(f"{rel}: sha256 {digest} differs from MANIFEST {manifest[name]['sha256']}")
            (HERE / "lists" / f"{name}.dat").write_text(text)
            manifest[name] = {"file": rel, "base": base, "seed": list_seed, "rows": N, "sha256": digest}
            print(f"{rel}: {N} rows, sha256 {digest}")
        lines = (HERE / "cards" / f"{base}.dat").read_text().splitlines()
        out = []
        for line in lines:
            key = line.split()[:1]
            if key == ["production_distribution"]:
                out += ["production_distribution particle_list", f"particle_list_file {rel}",
                        "particle_list_position true"]
            elif key == ["seed"]:
                out.append(f"seed {card_seed}")
            else:
                out.append(line)
        out[0] = f"# particle_list base card, generated by make_lists.py from {base}.dat."
        (HERE / "cards" / f"{stem}.dat").write_text("\n".join(out) + "\n")
    if not args.cards_only:
        man_path.write_text(json.dumps(manifest, indent=1) + "\n")


if __name__ == "__main__":
    main()
